@ ---------------------------------------------------------------------------
@ GBA Studio — crt0 (M0)
@
@ ROM layout produced by this file plus runtime/linker/gba.ld:
@   0x08000000  ARM branch to 0x080000C0
@   0x08000004  156-byte Nintendo logo (fixed hardware constant, see GBATEK)
@   0x080000A0  title / game code / maker code / 0x96 / version / complement
@   0x080000C0  _start
@
@ The branch word below is the canonical encoding of "b _start" when the
@ header is exactly 0xC0 bytes:  (0x080000C0 - 0x08000008) / 4 = 0x2E.
@ runtime/linker/gba.ld asserts that _start really lands on 0x080000C0.
@
@ Target is ARM7TDMI (ARMv4T): no conditional BX, no BLX register.
@ ---------------------------------------------------------------------------

    .arm

@ ==== ROM header ==========================================================
    .section .rom_header, "a", %progbits
    .global __rom_header
__rom_header:
    .word   0xEA00002E                  @ b _start  (offset 0x2E * 4 + 8)

    @ --- Nintendo logo, 156 bytes. Required by real hardware. ---
    .byte   0x24,0xFF,0xAE,0x51,0x69,0x9A,0xA2,0x21,0x3D,0x84,0x82,0x0A,0x84,0xE4,0x09,0xAD
    .byte   0x11,0x24,0x8B,0x98,0xC0,0x81,0x7F,0x21,0xA3,0x52,0xBE,0x19,0x93,0x09,0xCE,0x20
    .byte   0x10,0x46,0x4A,0x4A,0xF8,0x27,0x31,0xEC,0x58,0xC7,0xE8,0x33,0x82,0xE3,0xCE,0xBF
    .byte   0x85,0xF4,0xDF,0x94,0xCE,0x4B,0x09,0xC1,0x94,0x56,0x8A,0xC0,0x13,0x72,0xA7,0xFC
    .byte   0x9F,0x84,0x4D,0x73,0xA3,0xCA,0x9A,0x61,0x58,0x97,0xA3,0x27,0xFC,0x03,0x98,0x76
    .byte   0x23,0x1D,0xC7,0x61,0x03,0x04,0xAE,0x56,0xBF,0x38,0x84,0x00,0x40,0xA7,0x0E,0xFD
    .byte   0xFF,0x52,0xFE,0x03,0x6F,0x95,0x30,0xF1,0x97,0xFB,0xC0,0x85,0x60,0xD6,0x80,0x25
    .byte   0xA9,0x63,0xBE,0x03,0x01,0x4E,0x38,0xE2,0xF9,0xA2,0x34,0xFF,0xBB,0x3E,0x03,0x44
    .byte   0x78,0x00,0x90,0xCB,0x88,0x11,0x3A,0x94,0x65,0xC0,0x7C,0x63,0x87,0xF0,0x3C,0xAF
    .byte   0xD6,0x25,0xE4,0x8B,0x38,0x0A,0xAC,0x72,0x21,0xD4,0xF8,0x07

    @ The project's own title, code and maker, generated by "gbs build" into
    @ rom_header.s. The default in this directory is what a build with no
    @ project behind it uses (the bring-up examples), and the assembler finds
    @ the generated one first because the build passes its directory first.
    .include "rom_header.s"
    .byte   0x96                        @ 0x0B2 fixed
    .byte   0x00                        @ 0x0B3 main unit code
    .byte   0x00                        @ 0x0B4 device type
    .space  7, 0x00                     @ 0x0B5 reserved
    .byte   0x00                        @ 0x0BC software version
    .byte   0x00                        @ 0x0BD complement, patched by tools/romfix.ps1
    .space  2, 0x00                     @ 0x0BE reserved
    @ total: 4 + 156 + 12 + 4 + 2 + 1 + 1 + 1 + 7 + 1 + 1 + 2 = 192 = 0xC0

@ ==== entry point =========================================================
    .section .text.startup, "ax", %progbits
    .global _start
    .type   _start, %function
_start:
    @ ---- 1. interrupts off ----
    mov     r0, #0x04000000
    add     r0, r0, #0x200              @ r0 = 0x04000200 (IE/IF/WAITCNT/IME)
    mov     r1, #0
    strh    r1, [r0, #8]                @ REG_IME  = 0
    strh    r1, [r0, #0]                @ REG_IE   = 0
    mvn     r1, #0
    strh    r1, [r0, #2]                @ REG_IF   = 0xFFFF (write 1 clears)

    @ ---- 2. force blank while we initialise ----
    mov     r0, #0x04000000
    mov     r1, #0x80                   @ DCNT_BLANK
    strh    r1, [r0, #0]                @ REG_DISPCNT

    @ ---- 2b. Cartridge wait states: deliberately NOT touched ----
    @ Writing REG_WAITCNT here was measured to hang on real hardware running
    @ from a flash cartridge: 0x4014 enables the ROM prefetch buffer, which
    @ carts that serve the ROM from PSRAM or an SD card cannot tolerate. The
    @ BIOS has already configured timing for the cartridge it booted from, and
    @ that configuration is both correct and the most compatible one.
    @ Code that knows its target cartridge may call gbs_hw_rom_timing() to
    @ trade compatibility for speed; see runtime/include/gba/hw.h.

    @ ---- 3. stacks ----
    @ 0x03007F00-0x03007FA0 IRQ stack, 0x03007F00 user/system stack
    @ (0x03007FA0-0x03007FFF belongs to the BIOS itself)
    msr     cpsr_c, #0xD2               @ IRQ mode, I and F disabled
    ldr     sp, =0x03007FA0
    msr     cpsr_c, #0xDF               @ System mode, I and F disabled
    ldr     sp, =0x03007F00

    @ ---- 4. copy .iwram from ROM to IWRAM ----
    ldr     r0, =__iwram_lma
    ldr     r1, =__iwram_start
    ldr     r2, =__iwram_size
    bl      __gbs_copy_words

    @ ---- 5. copy .data from ROM to EWRAM ----
    ldr     r0, =__data_lma
    ldr     r1, =__data_start
    ldr     r2, =__data_size
    bl      __gbs_copy_words

    @ ---- 6. clear .bss in EWRAM ----
    ldr     r0, =__bss_start
    ldr     r1, =__bss_size
    bl      __gbs_clear_words

    @ ---- 7. install the user IRQ vector (BIOS reads 0x03007FFC) ----
    ldr     r0, =gbs_irq_handler
    ldr     r1, =0x03007FFC
    str     r0, [r1]

    @ ---- 8. let the CPU take interrupts ----
    msr     cpsr_c, #0x1F               @ System mode, I and F enabled

    @ ---- 9. enter C (interworking-safe: works for ARM or Thumb AgbMain) ----
    ldr     r0, =AgbMain
    mov     lr, pc
    bx      r0
1:  b       1b                          @ AgbMain must never return

@ ==== helpers =============================================================
    .type   __gbs_copy_words, %function
__gbs_copy_words:                       @ r0 = src, r1 = dst, r2 = byte count (multiple of 4)
    cmp     r2, #0
    beq     2f
1:  ldr     r3, [r0], #4
    str     r3, [r1], #4
    subs    r2, r2, #4
    bne     1b
2:  bx      lr

    .type   __gbs_clear_words, %function
__gbs_clear_words:                      @ r0 = dst, r1 = byte count (multiple of 4)
    mov     r2, #0
    cmp     r1, #0
    beq     2f
1:  str     r2, [r0], #4
    subs    r1, r1, #4
    bne     1b
2:  bx      lr

@ ==== IRQ dispatcher (IWRAM, ARM) ========================================
@ The BIOS jumps here from a fixed vector; ROM wait states make a ROM-resident
@ handler unreliable, so this lives in IWRAM and is copied there by step 4.
@ It must stay small: the IRQ stack is only 0xA0 bytes.
    .section .iwram.text, "ax", %progbits
    .arm
    .global gbs_irq_handler
    .type   gbs_irq_handler, %function
gbs_irq_handler:
    stmfd   sp!, {r0-r3, r4-r7, lr}
    mov     r4, #0x04000000
    add     r4, r4, #0x200              @ r4 = 0x04000200
    ldrh    r0, [r4, #0]                @ r0 = REG_IE
    ldrh    r1, [r4, #2]                @ r1 = REG_IF
    and     r5, r1, r0                  @ pending and enabled
    strh    r1, [r4, #2]                @ acknowledge every raised flag
    ldr     r6, =gbs_isr_table
    mov     r7, #0                      @ bit index
1:  cmp     r7, #14
    bge     3f
    movs    r5, r5, lsr #1              @ carry = next pending bit
    bcs     2f
    add     r7, r7, #1
    b       1b
2:  ldr     r3, [r6, r7, lsl #2]
    cmp     r3, #0
    beq     4f
    mov     lr, pc
    bx      r3                          @ r0-r3 may be clobbered, state is in r4-r7
4:  add     r7, r7, #1
    b       1b
3:  ldmfd   sp!, {r0-r3, r4-r7, lr}
    bx      lr

    .end
