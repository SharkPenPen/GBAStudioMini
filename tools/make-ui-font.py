#!/usr/bin/env python3
"""Generate a native-size UI face header (ASCII + CJK level-1) from BDF or TTF.

BDF is parsed directly. TTF is rendered with Pillow at the requested native
size; this is only acceptable because Firefly 14 stores native 14px strikes.
No scaling is performed: the requested size must be the font's native size.
"""
import argparse
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def cjk_codes(path):
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    codes = set(int(m, 16) for m in re.findall(r"\{0x([0-9A-Fa-f]+),", text))
    codes.update(int(m, 16) for m in re.findall(r"^([0-9A-Fa-f]{4,6})$", text, re.M))
    return sorted(codes)


def parse_bdf(path):
    lines = Path(path).read_text(encoding="utf-8", errors="replace").splitlines()
    glyphs = {}
    cur = None
    in_bitmap = False
    bitmap = []
    for raw in lines:
        line = raw.strip()
        if in_bitmap:
            if line == "ENDCHAR":
                if cur is not None:
                    cur["bitmap"] = bitmap
                    glyphs[cur["encoding"]] = cur
                cur = None
                in_bitmap = False
                bitmap = []
            elif line:
                bitmap.append(line)
            continue
        parts = line.split()
        if not parts:
            continue
        key = parts[0]
        if key == "STARTCHAR":
            cur = {"name": " ".join(parts[1:])}
        elif key == "ENCODING" and cur is not None:
            cur["encoding"] = int(parts[1])
        elif key == "DWIDTH" and cur is not None:
            cur["dwidth"] = int(parts[1])
        elif key == "BBX" and cur is not None:
            cur["bbx"] = tuple(int(x) for x in parts[1:5])
        elif key == "BITMAP":
            in_bitmap = True
    return glyphs


def bdf_cell(g, size):
    w, h, xoff, yoff = g["bbx"]
    cell = [[0] * size for _ in range(size)]
    rows = []
    for line in g.get("bitmap", []):
        raw = bytes.fromhex(line)
        bits = []
        for byte in raw:
            for bit in range(7, -1, -1):
                bits.append((byte >> bit) & 1)
        rows.append(bits[:w])
    top = size - (yoff + h)
    for y in range(h):
        cy = top + y
        if cy < 0 or cy >= size:
            continue
        for x in range(w):
            cx = x + xoff
            if cx < 0 or cx >= size:
                continue
            if y < len(rows) and x < len(rows[y]) and rows[y][x]:
                cell[cy][cx] = 1
    adv = g.get("dwidth", size // 2)
    if adv <= 0:
        adv = size // 2
    return cell, adv


def ttf_cell(font, cp, size):
    ch = chr(cp)
    img = Image.new("L", (size, size), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 0), ch, font=font, fill=255)
    cell = [[1 if img.getpixel((x, y)) > 127 else 0 for x in range(size)]
            for y in range(size)]
    adv = int(round(font.getlength(ch)))
    if adv <= 0:
        adv = size // 2
    return cell, adv


def emit(name, size, entries, out):
    lines = []
    lines.append("// Generated by tools/make-ui-font.py - do not edit.\n")
    lines.append("#pragma once\n")
    lines.append('#include "render/ui_face.h"\n\n')
    lines.append("namespace eng {\n")
    lines.append(f"constexpr int {name}W = {size};\n")
    lines.append(f"constexpr int {name}H = {size};\n")
    lines.append(f"constexpr int {name}Count = {len(entries)};\n")
    lines.append(f"inline const UiFaceGlyph {name}[] = {{\n")
    for cp, cell, adv in entries:
        vals = []
        for row in cell:
            v = 0
            for x, bit in enumerate(row):
                if bit:
                    v |= 1 << x
            vals.append(str(v))
        while len(vals) < 16:
            vals.append("0")
        lines.append(f"  {{0x{cp:04X}, {{{','.join(vals)}}}, {adv}}},\n")
    lines.append("};\n")
    lines.append("}  // namespace eng\n")
    Path(out).write_text("".join(lines), encoding="utf-8")
    print(f"{out}: {len(entries)} glyphs, {size}x{size}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bdf")
    ap.add_argument("--ttf")
    ap.add_argument("--size", type=int, required=True)
    ap.add_argument("--codes", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    codes = list(range(32, 127)) + cjk_codes(args.codes)
    codes = sorted(set(codes))
    entries = []
    if args.bdf:
        glyphs = parse_bdf(args.bdf)
        for cp in codes:
            g = glyphs.get(cp)
            if g is None or "bbx" not in g:
                continue
            cell, adv = bdf_cell(g, args.size)
            entries.append((cp, cell, min(255, adv)))
    else:
        font = ImageFont.truetype(args.ttf, args.size)
        for cp in codes:
            cell, adv = ttf_cell(font, cp, args.size)
            entries.append((cp, cell, min(255, adv)))
    emit(args.name, args.size, entries, args.out)


if __name__ == "__main__":
    main()
